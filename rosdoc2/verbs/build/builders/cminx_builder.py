import logging
import os
import shutil
import subprocess
import sys

from ..builder import Builder

logger = logging.getLogger('rosdoc2')

CMINX_ROOT_INDEX = """\
.. Generated by rosdoc2.verbs.build.builders.CMinxBuilder.

{underline}
{title}
{underline}

.. toctree::
   :maxdepth: 2

{entries}"""


class CMinxBuilder(Builder):
    """
    Builder for CMinx, which generates Sphinx rst files from CMake doc comments.

    CMinx documents CMake functions, macros, and variables which are preceded by
    a block comment of the form ``#[[[ ... #]]``. The generated rst files are
    later included by the Sphinx builder. This builder only runs if the setting
    'use_cminx' is true.

    Supported keys for the builder_entry_dictionary include:

    - name (str) (required)
      - name of the documentation, used in reference to the content generated by this builder
    - builder (str) (required)
      - required for all builders, must be 'cminx' to use this class
    - cminx_input_dir (str) (optional)
      - relative path, from the package.xml directory, of the directory containing
        .cmake files to document. Defaults to 'cmake'.
    - cminx_settings_file (str) (optional)
      - relative path, from the package.xml directory, of a CMinx settings YAML file.
    """

    def __init__(self, builder_name, builder_entry_dictionary, build_context):
        """Construct a new CMinxBuilder."""
        super(CMinxBuilder, self).__init__(
            builder_name,
            builder_entry_dictionary,
            build_context)

        assert self.builder_type == 'cminx'
        self.name = self.name or self.build_context.package.name + ' CMake API'
        self.output_dir = self.output_dir or 'generated/cminx'
        self.cminx_input_dir = 'cmake'
        self.cminx_settings_file = None

        # Process keys.
        configuration_file_path = build_context.configuration_file_path
        package_directory = os.path.dirname(build_context.package.filename)
        for key, value in builder_entry_dictionary.items():
            if key in ['name', 'output_dir']:
                continue
            if key == 'cminx_input_dir':
                logger.info(f'User specified cminx_input_dir as "{value}"')
                if value:
                    if not os.path.isdir(os.path.join(package_directory, value)):
                        raise RuntimeError(
                            f"Error processing file '{configuration_file_path}', expected setting "
                            f"'cminx_input_dir' to be a directory under {package_directory}")
                    self.cminx_input_dir = value
            elif key == 'cminx_settings_file':
                if not value:
                    continue
                if not os.path.isfile(os.path.join(package_directory, value)):
                    raise RuntimeError(
                        f"Error processing file '{configuration_file_path}', expected setting "
                        f"'cminx_settings_file' to be a file under {package_directory}")
                self.cminx_settings_file = value
            else:
                raise RuntimeError(f"Error the CMinx builder does not support key '{key}'")

    def build(self, *, doc_build_folder, output_staging_directory):
        """Actually do the build."""
        if not self.build_context.use_cminx:
            logger.debug("The setting 'use_cminx' is not true, so skipping cminx.")
            return None

        package_directory = os.path.dirname(self.build_context.package.filename)
        input_dir = os.path.abspath(os.path.join(package_directory, self.cminx_input_dir))
        has_cmake_files = False
        for _, _, files in os.walk(input_dir):
            if any(file.lower().endswith('.cmake') for file in files):
                has_cmake_files = True
                break
        if not has_cmake_files:
            logger.info(
                f"No .cmake files found in '{input_dir}', therefore cminx will not be run.")
            return None

        cminx_executable = shutil.which('cminx')
        if cminx_executable is None:
            logger.warning(
                "The setting 'use_cminx' is true, but the 'cminx' executable was not found. "
                'CMinx is a rosdoc2 dependency; check that it is installed and on PATH. '
                'CMake documentation will not be generated.')
            return None

        cminx_output_dir = os.path.abspath(os.path.join(doc_build_folder, 'cminx_output'))
        os.makedirs(cminx_output_dir, exist_ok=True)

        cmd = [
            cminx_executable,
            '-r',
            '-p', self.build_context.package.name,
            '-o', cminx_output_dir,
        ]
        if self.cminx_settings_file:
            cmd.extend(['-s', os.path.abspath(
                os.path.join(package_directory, self.cminx_settings_file))])
        cmd.append(input_dir)

        logger.info(f"Running cminx: '{' '.join(cmd)}' in '{doc_build_folder}'")
        completed_process = subprocess.run(
            cmd, cwd=doc_build_folder, stdout=sys.stdout, stderr=sys.stderr)
        msg = f"cminx exited with return code '{completed_process.returncode}'"
        if completed_process.returncode != 0:
            logger.warning(msg)
            return None
        logger.info(msg)

        # cminx does not generate an index.rst for directories without .cmake files, which
        # is common (for example 'cmake/' with only subdirectories). Generate one in that case
        # so that the sphinx builder has a single entry point.
        root_index = os.path.join(cminx_output_dir, 'index.rst')
        if not os.path.isfile(root_index):
            subdirs = sorted(
                entry.name for entry in os.scandir(cminx_output_dir)
                if entry.is_dir() and os.path.isfile(os.path.join(entry.path, 'index.rst')))
            if not subdirs:
                logger.info('cminx generated no documentation.')
                return None
            title = self.build_context.package.name
            with open(root_index, 'w') as f:
                f.write(CMINX_ROOT_INDEX.format(
                    title=title,
                    underline='#' * len(title),
                    entries=''.join(f'   {subdir}/index\n' for subdir in subdirs)))

        # Return the directory into which cminx generated.
        return cminx_output_dir
